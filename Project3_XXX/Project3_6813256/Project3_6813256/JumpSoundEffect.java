package Project3_6813256;

import javax.sound.sampled.AudioSystem;
import javax.sound.sampled.AudioFormat;
import javax.sound.sampled.Clip;
import javax.sound.sampled.FloatControl;

/** Small synthesized retro chirp that plays when a jump begins. */
public final class JumpSoundEffect implements AutoCloseable {
    private static final int SAMPLE_RATE = 22_050;
    private static final double DURATION_SECONDS = 0.14;
    private Clip clip;

    public JumpSoundEffect() {  // create and assign clip object as a member
        try {
            int frameCount = (int) (SAMPLE_RATE * DURATION_SECONDS);
            byte[] pcm = createJumpTone(frameCount);     // audio bytes
            AudioFormat format = new AudioFormat(SAMPLE_RATE, 16, 1, true, false);
            clip = AudioSystem.getClip();
            clip.open(format, pcm, 0, pcm.length);   // apply generated bytes to format
            if (clip.isControlSupported(FloatControl.Type.MASTER_GAIN)) {
                FloatControl gain = (FloatControl) clip.getControl(FloatControl.Type.MASTER_GAIN);
                gain.setValue(Math.max(gain.getMinimum(), Math.min(gain.getMaximum(), -8.0f)));
            }
        } catch (Exception exception) {
            clip = null;
            System.err.println("Could not initialize jump sound: " + exception.getMessage());
        }
    }

    public void play(boolean soundEnabled) {   // clip can be played multiple times and interupt previous command
        if (!soundEnabled || clip == null || !clip.isOpen()) {
            return;
        }
        if (clip.isRunning()) {
            clip.stop();
        }
        clip.setFramePosition(0);
        clip.start();
    }

    private byte[] createJumpTone(int frameCount) {    // create audio by byte
        byte[] pcm = new byte[frameCount * 2];
        for (int frame = 0; frame < frameCount; frame++) {
            double progress = frame / (double) frameCount;    // % frame finished
            double time = frame / (double) SAMPLE_RATE;       // converted frame to s = f/(f/s)
            double frequencyStart = 390.0;
            double frequencyEnd = 980.0;
            double phase = 2.0 * Math.PI * (frequencyStart * time   // 2pif = w(angular velocity)
                    + (frequencyEnd - frequencyStart)
                    * time * time / (2.0 * DURATION_SECONDS));    // integrate ft dt = (f t^2/2)range
            double envelope = Math.pow(1.0 - progress, 1.6);
            short sample = (short) (Math.sin(phase) * envelope * 14_000);
            pcm[frame * 2] = (byte) (sample & 0xff);
            pcm[frame * 2 + 1] = (byte) ((sample >>> 8) & 0xff);
        }
        return pcm;
    }

    @Override
    public void close() {
        if (clip != null) {
            clip.stop();
            clip.close();
            clip = null;
        }
    }
}
